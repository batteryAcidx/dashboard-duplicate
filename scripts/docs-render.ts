// Turns the guides and the start-here page into Markdown. The in-app Wiki and the docs folder
// are made from the same data, so they can never disagree. Run `npm run docs` (in engine-tests) after changing a guide.
import { INTEGRATIONS } from '../src/integrations/catalog';
import type { Guide, GuideStep } from '../src/integrations/guide';
import { START_HERE } from '../src/integrations/wiki';

export const DOC_CONTEXT = { backendUrl: 'https://<your-project-ref>.supabase.co', appUrl: 'https://dashboard.wedgescale.com' };
const BANNER = '<!-- Generated by `npm run docs` from src/integrations. Do not edit by hand: change the guide and run it again. -->\n\n';

const step = (s: GuideStep, n?: number): string => {
  const out: string[] = [n ? `### ${n}. ${s.title}` : `### ${s.title}`, ''];
  for (const p of s.body) out.push(p, '');
  for (const c of s.copy ?? []) out.push(`**${c.label}**`, '', '```', c.value, '```', '');
  if (s.link) out.push(`[${s.link.label}](${s.link.href})`, '');
  if (s.note) out.push(`> ${s.note}`, '');
  return out.join('\n');
};

export function renderGuide(id: string): string {
  const info = INTEGRATIONS.find((i) => i.id === id)!;
  const g: Guide = info.guide(DOC_CONTEXT);
  const out: string[] = [
    BANNER + `# ${info.name}`, '', `*${info.tagline}*`, '', g.intro, '',
    `**How long:** ${g.time}  `, `**Cost:** ${g.cost}`, '',
    '## What it turns on', '', ...info.unlocks.map((u) => `- ${u}`), '', '## Without it', '', info.withoutIt, '',
    '## Steps', '', ...g.steps.map((s, i) => step(s, i + 1)),
    '## How to know it works', '', ...g.checks.map((c) => `- ${c}`), '',
  ];
  if (g.later?.length) out.push('## Later, not needed yet', '', ...g.later.map((s) => step(s)));
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

export function renderStart(): string {
  const out: string[] = [BANNER + '# Start here', '', 'The order to do things in. You do not need a client for most of it, and each service is optional.', ''];
  START_HERE.forEach((p, i) => {
    out.push(`## ${i + 1}. ${p.title}`, '', p.why, '', ...p.items.map((it) => `- ${it}`), '');
  });
  return out.join('\n').trimEnd() + '\n';
}

export const DOC_FILES: Record<string, () => string> = {
  'START-HERE.md': renderStart,
  'SETUP-STRIPE.md': () => renderGuide('stripe'),
  'SETUP-GOOGLE-CALENDAR.md': () => renderGuide('google_calendar'),
  'SETUP-EMAIL.md': () => renderGuide('email'),
  'SETUP-TWILIO.md': () => renderGuide('twilio'),
  'SETUP-CALL-FORWARDING.md': () => renderGuide('call_forwarding'),
};
